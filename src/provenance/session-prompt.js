import fs from 'node:fs';

/**
 * Reads the first prompt of a session straight from its transcript, for display only.
 *
 * This is the one place where conversation text is read. It is read when the user selects a
 * node, returned to the local window, and kept nowhere: it is never written to SQLite, to the
 * scan state or to a log (see AGENTS.md, "Zero Raw Conversation Persistence").
 */

/** Only the start of a transcript is read; the first prompt is at the top. */
const MAX_BYTES = 4 * 1024 * 1024;
export const MAX_PROMPT_CHARS = 2000;

/** Blocks a client adds around the user's words (command wrappers, reminders, context). */
const WRAPPER_BLOCK =
  /<(local-command-[a-z-]+|command-[a-z-]+|system-reminder|environment_context|user_instructions|ide_[a-z_]+)>[\s\S]*?<\/\1>/g;

function cleanPromptText(text) {
  const cleaned = String(text || '').replace(WRAPPER_BLOCK, '').trim();
  if (!cleaned || cleaned.startsWith('Caveat: The messages below were generated by the user while running local commands')) {
    return '';
  }
  return cleaned;
}

/** Joins the plain text parts of a message body; tool results and images are ignored. */
function textOfContent(content) {
  if (typeof content === 'string') {
    return content;
  }
  if (!Array.isArray(content)) {
    return '';
  }
  return content
    .filter((part) => part && (part.type === 'text' || part.type === 'input_text') && typeof part.text === 'string')
    .map((part) => part.text)
    .join('\n');
}

/** The user's text in one transcript record, or '' when the record is not a user prompt. */
export function userTextOfRecord(record) {
  if (!record || typeof record !== 'object' || record.isMeta || record.isSidechain) {
    return '';
  }
  // Claude Code: { type: 'user', message: { role: 'user', content } }
  if (record.message && record.message.role === 'user' && record.type !== 'assistant') {
    return cleanPromptText(textOfContent(record.message.content));
  }
  // Codex rollout: { type: 'response_item', payload: { type: 'message', role: 'user', content } }
  const payload = record.payload;
  if (payload && payload.type === 'message' && payload.role === 'user') {
    return cleanPromptText(textOfContent(payload.content));
  }
  if (payload && payload.type === 'user_message' && typeof payload.message === 'string') {
    return cleanPromptText(payload.message);
  }
  // Plain message records: { type: 'message', role: 'user', content }
  if (record.role === 'user' && !record.message) {
    return cleanPromptText(textOfContent(record.content));
  }
  return '';
}

/**
 * @param {object} session a session model (externalSessionId, sourcePath)
 * @returns {{available: boolean, text?: string, truncated?: boolean, reason?: string}}
 */
export function readSessionFirstPrompt(session, { maxChars = MAX_PROMPT_CHARS } = {}) {
  const sourcePath = session && session.sourcePath;
  if (!sourcePath || !/\.jsonl$/i.test(sourcePath)) {
    return { available: false, reason: 'NOT_RECORDED_FOR_THIS_APP' };
  }
  let head;
  try {
    const st = fs.lstatSync(sourcePath);
    if (!st.isFile()) {
      return { available: false, reason: 'TRANSCRIPT_NOT_FOUND' };
    }
    const fd = fs.openSync(sourcePath, 'r');
    try {
      const buffer = Buffer.alloc(Math.min(st.size, MAX_BYTES));
      const read = fs.readSync(fd, buffer, 0, buffer.length, 0);
      head = buffer.toString('utf8', 0, read);
    } finally {
      fs.closeSync(fd);
    }
  } catch (err) {
    return {
      available: false,
      reason: err.code === 'EACCES' || err.code === 'EPERM' ? 'TRANSCRIPT_NOT_READABLE' : 'TRANSCRIPT_NOT_FOUND'
    };
  }

  const wantedId = String(session.externalSessionId || '');
  for (const rawLine of head.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line[0] !== '{') {
      continue;
    }
    let record;
    try {
      record = JSON.parse(line);
    } catch {
      continue; // A cut-off or malformed line
    }
    // One file can hold several sessions; a record that names another session is not ours
    const recordSession = record.sessionId || record.session_id;
    if (recordSession && wantedId && String(recordSession) !== wantedId) {
      continue;
    }
    const text = userTextOfRecord(record);
    if (text) {
      return {
        available: true,
        text: text.slice(0, maxChars),
        truncated: text.length > maxChars
      };
    }
  }
  return { available: false, reason: 'NO_PROMPT_IN_TRANSCRIPT' };
}
